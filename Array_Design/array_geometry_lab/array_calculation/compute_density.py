"""
Computes packing_density_per_area_um-2 for every row of sweep_results.csv and writes
sweep_results_with_density.csv (a new derived file -- sweep_results.csv itself is
never modified BY THIS SCRIPT; as of degeneracy_filter.py/clean_sweep_results.py,
sweep_results.csv is already pre-cleaned at the root, so this script's own
degeneracy exclusion is now expected to be a no-op / safety net, not the primary
place exclusion happens -- see ../degeneracy_filter.py and
../clean_sweep_results.py).

AUDIT FIX (Defect A -- the density metric was apples-to-oranges across families):
packing_density_per_area_um-2 = N_actual / bounding_area_um2, where bounding_area_um2
is now ONE family-agnostic formula -- the buffered convex hull of the ACTUAL
generated hole coordinates -- applied IDENTICALLY to every one of the 10 families.
This module used to compute bounding_area_um2 with a DIFFERENT formula per family
(unit-cell-area x count for square/hexagonal/rectangular, a buffered enclosing
circle for concentric/ring_offset_concentric, a buffered convex hull for the
remaining five) -- confirmed by direct controlled test that this made the SAME
physical arrangement score differently depending on which formula its family
happened to use (1.56x-2.25x, worst at small N). See ../degeneracy_filter.py's own
module docstring for the full mechanism and the verification that geometrically
identical arrangements across different families now produce bit-identical density.

For EVERY family, the ACTUAL hole coordinates are regenerated by calling that
family's own generators/*.py generate() function with the exact same
(N_requested, a_hole_um, spacing_params, seed) recorded in that row -- these
generators are deterministic given those inputs (stochastic families are deterministic
given the seed), so this reproduces the identical geometry sweep/run_sweep.py itself
evaluated for that row, not an approximation of it.

Run:  python3 compute_density.py
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))  # array_calculation/ -- this file
                          # lives at this layer's own root now (moved out of the old
                          # comparison_metric/ folder, which was split across
                          # calculation (this file, a raw geometric quantity) and
                          # evaluation (gates/metrics, which rank/threshold) -- see
                          # array_calculation/README.md.
LAB_ROOT = os.path.dirname(HERE)  # array_geometry_lab/
sys.path.insert(0, HERE)
import degeneracy_filter  # noqa: E402 -- single source of truth for the area
                          # formulas AND the degeneracy-exclusion logic; see that
                          # module's own docstring for the full mechanism writeup.
                          # Co-located with this file in array_calculation/ now.

DATA_DIR = os.path.join(LAB_ROOT, "array_data", "theoretical_data")
IN_CSV = os.path.join(DATA_DIR, "sweep_results.csv")
OUT_CSV = os.path.join(DATA_DIR, "sweep_results_with_density.csv")
EXCLUDED_LOG_CSV = os.path.join(DATA_DIR, "degenerate_rows_excluded.csv")
PRECONTAMINATED_LEGACY_CSV = os.path.join(
    DATA_DIR, "sweep_results_with_density_PRECONTAMINATED_legacy.csv")


def compute_row_density(row):
    """Returns (density, exclusion_reason). exclusion_reason is None for rows that
    pass degeneracy_filter.is_degenerate() (density is then a real finite number).
    For rows that FAIL it, density is np.nan AND exclusion_reason is a non-empty
    string -- such rows are removed from the output entirely by main() (not left in
    as a silent NaN row) and logged to degenerate_rows_excluded.csv. Since
    sweep_results.csv is now pre-cleaned at the root (see module docstring), this is
    expected to find nothing to exclude on a normal run -- it stays here as a
    defensive check, not the primary enforcement point anymore.

    AUDIT FIX (Defect A): every family now regenerates coordinates and computes
    density via degeneracy_filter.convex_hull_area() UNCONDITIONALLY -- no more
    per-family branching on which area formula to use (see degeneracy_filter.py's
    own module docstring)."""
    degenerate, reason = degeneracy_filter.is_degenerate(row)
    if degenerate:
        return np.nan, reason

    family = row.family
    kwargs = degeneracy_filter.parse_spacing_params(row.spacing_params)
    N_actual = int(row.N_actual)

    gen_kwargs = dict(kwargs)
    if pd.notna(row.seed):
        gen_kwargs["seed"] = int(row.seed)
    # is_degenerate() above already regenerated this exact geometry (and verified
    # its N_actual matches the row's own) as part of its own check -- generate() is
    # deterministic given the same inputs, so this reproduces identical
    # coordinates, not an independent/divergent computation.
    coords, meta = degeneracy_filter.GEN_FUNCS[family](
        N=int(row.N_requested), a_hole_um=row.a_hole_um, **gen_kwargs)
    area = degeneracy_filter.convex_hull_area(coords, row.a_hole_um)

    if not np.isfinite(area) or area <= 0:
        return np.nan, f"area computation returned {area}"
    return N_actual / area, None


def preserve_legacy(path):
    """Standard project convention (see sweep/run_sweep.py's own preserve_legacy):
    copies path to path_legacyN.csv (auto-incrementing) before it gets overwritten,
    so nothing is ever silently lost -- used here for degenerate_rows_excluded.csv,
    which this run is about to overwrite with a (now expected to be near-empty)
    fresh copy now that sweep_results.csv is pre-cleaned at the root."""
    if not os.path.exists(path):
        return
    import shutil
    i = 1
    legacy_path = path.replace(".csv", f"_legacy{i}.csv")
    while os.path.exists(legacy_path):
        i += 1
        legacy_path = path.replace(".csv", f"_legacy{i}.csv")
    shutil.copy2(path, legacy_path)
    print(f"preserved predecessor -> {legacy_path}")


def main():
    # PRECONTAMINATED_LEGACY_CSV is a ONE-TIME snapshot of the density file as it
    # was before the physics fix (see README.md, "Known defect and its fix") --
    # never overwrite it once it exists, or that historical before/after record is
    # destroyed. A genuinely new contamination event would need a new, differently
    # named snapshot, not a silent overwrite of this one.
    if os.path.exists(OUT_CSV) and not os.path.exists(PRECONTAMINATED_LEGACY_CSV):
        import shutil
        shutil.copy2(OUT_CSV, PRECONTAMINATED_LEGACY_CSV)
        print(f"preserved predecessor (contaminated -- see comparison_metric/README.md) "
              f"-> {PRECONTAMINATED_LEGACY_CSV}")

    preserve_legacy(EXCLUDED_LOG_CSV)

    df = pd.read_csv(IN_CSV)
    print(f"loaded {len(df)} rows from {IN_CSV}")

    densities = []
    reasons = []
    n_done = 0
    for row in df.itertuples():
        d, reason = compute_row_density(row)
        densities.append(d)
        reasons.append(reason)
        n_done += 1
        if n_done % 1000 == 0:
            print(f"  {n_done}/{len(df)} rows done")
    df["packing_density_per_area_um-2"] = densities
    df["_exclusion_reason"] = reasons

    excluded_mask = df["_exclusion_reason"].notna()
    excluded = df[excluded_mask][["family", "N_requested", "N_actual", "spacing_params",
                                  "a_hole_um", "seed", "M", "_exclusion_reason"]].rename(
        columns={"_exclusion_reason": "reason"})
    excluded.to_csv(EXCLUDED_LOG_CSV, index=False)
    print(f"\nwrote {EXCLUDED_LOG_CSV} ({len(excluded)} rows excluded by the degeneracy filter, "
          f"{len(excluded)}/{len(df)} = {100.0*len(excluded)/len(df):.1f}%)")
    print("excluded rows per family:")
    print(excluded.family.value_counts().to_string())

    # Excluded rows are REMOVED from the density-bearing output entirely (per the
    # task brief: "not given a null/NaN density and left in") -- they were logged
    # above precisely so this removal is auditable, not silent.
    df = df[~excluded_mask].drop(columns=["_exclusion_reason"]).reset_index(drop=True)
    assert df["packing_density_per_area_um-2"].notna().all(), (
        "a row with NaN density survived the exclusion filter -- every NaN-density "
        "path in compute_row_density() must also set a reason and be excluded; this "
        "should be impossible, investigate compute_row_density() before proceeding.")

    # --- Step 3: independent physical-validity assertion -- the safety net for a
    # SECOND, different bug, not a restatement of the degeneracy filter above. Must
    # not be skipped even though it looks redundant with the filter.
    open_area_fraction = (np.pi * (df.a_hole_um / 2.0) ** 2 *
                          df["packing_density_per_area_um-2"])
    TOLERANCE = 1.0001
    violations = df[open_area_fraction > TOLERANCE].copy()
    if len(violations) > 0:
        violations["open_area_fraction"] = open_area_fraction[open_area_fraction > TOLERANCE]
        print(f"\n*** ASSERTION FAILED: {len(violations)}/{len(df)} rows still have "
              f"open_area_fraction > {TOLERANCE} AFTER the degeneracy filter. ***")
        print("This means a SECOND, DIFFERENT bug exists beyond the N_actual-collapse "
              "case the degeneracy filter targets -- STOPPING. sweep_results_with_density.csv "
              "is NOT being (re)written by this run; the previous file (if any) is unchanged "
              "beyond the just-created *_PRECONTAMINATED_legacy.csv copy.")
        print("\nviolations per family:")
        print(violations.family.value_counts().to_string())
        print("\nworst offending rows:")
        print(violations[["family", "N_requested", "N_actual", "spacing_params", "a_hole_um",
                          "packing_density_per_area_um-2", "open_area_fraction"]]
              .sort_values("open_area_fraction", ascending=False).head(25).to_string())
        sys.exit(1)
    print(f"\nassertion passed: all {len(df)} surviving rows have "
          f"open_area_fraction <= {TOLERANCE}.")

    df.to_csv(OUT_CSV, index=False)
    print(f"wrote {OUT_CSV} ({len(df)} rows, original sweep_results.csv untouched)")

    print("\n--- per-family density sanity check (min / max / mean, um^-2) ---")
    for family, g in df.groupby("family"):
        d = g["packing_density_per_area_um-2"].dropna()
        n_nan = g["packing_density_per_area_um-2"].isna().sum()
        if len(d) == 0:
            print(f"{family:25s} ALL NaN ({n_nan} rows) -- investigate")
            continue
        print(f"{family:25s} min={d.min():.3e}  max={d.max():.3e}  mean={d.mean():.3e}  "
              f"(n={len(d)}, n_nan={n_nan})")

    # Closed-form packing-fraction spot check: at the tightest tested spacing for
    # square/hexagonal, packing_density_per_area_um-2 * (pi/4 * a_hole_um**2) should
    # be close to (but not exceeding by much) the known max theoretical packing
    # fraction for that lattice -- square ~78.5% (pi/4), hexagonal ~90.7%
    # (pi/(2*sqrt(3))) -- since holes cannot be packed denser than physical circles
    # allow. Post-Defect-A-fix, this now checks the BUFFERED-CONVEX-HULL density
    # formula (the same one every family uses), not the retired unit-cell formula --
    # a real, if usually small, finite-N boundary effect is expected now (the old
    # unit-cell formula had none, since N_actual cancelled out of it exactly; the
    # hull formula's buffer compensates for but does not perfectly cancel boundary
    # effects at finite N), so this remains an UPPER-BOUND sanity check ("never
    # exceeds the physical max"), not an exact-value check. "Tightest tested
    # spacing" here means the highest a_hole_um/pitch_um ratio STRICTLY BELOW 1.0,
    # not the smallest pitch outright: at ratio==1.0 (holes exactly touching),
    # base_generator.reject_overlapping()'s own tie-break rejects any point
    # <= a_hole_um from an already-kept one, which throws out roughly half the
    # lattice at exact tangency and would make the realized fraction look
    # artificially low -- not a fair test of the density FORMULA itself, which is
    # what this check is for. Largest tested N is preferred among ties at that ratio
    # since finite-lattice edge effects shrink relatively as N grows, giving the
    # closest available approximation to the infinite-lattice theoretical fraction.
    # This is a check on the density DEFINITION's sanity, not on any gate.
    print("\n--- closed-form packing-fraction spot check (tightest tested spacing, ratio<1.0) ---")
    for family, theoretical_max in [("square", np.pi / 4), ("hexagonal", np.pi / (2 * np.sqrt(3)))]:
        sub = df[df.family == family].copy()
        sub["pitch_um"] = sub.spacing_params.map(lambda s: degeneracy_filter.parse_spacing_params(s).get("pitch_um"))
        sub["ratio"] = sub.a_hole_um / sub.pitch_um
        valid = sub[sub.ratio < 1.0]
        tightest_ratio = valid.ratio.max()
        tsub = valid[np.isclose(valid.ratio, tightest_ratio)]
        row0 = tsub.loc[tsub.N_requested.idxmax()]
        hole_area = np.pi / 4.0 * row0.a_hole_um ** 2
        frac = row0["packing_density_per_area_um-2"] * hole_area
        status = "OK" if frac <= theoretical_max * 1.05 else "SUSPICIOUS -- exceeds theoretical max"
        print(f"{family:10s} pitch_um={row0.pitch_um:.1f}  a_hole_um={row0.a_hole_um:.1f}  "
              f"ratio={row0.ratio:.3f}  N_requested={int(row0.N_requested)}  N_actual={int(row0.N_actual)}  "
              f"realized_packing_fraction={frac:.3f}  theoretical_max={theoretical_max:.3f}  [{status}]")


if __name__ == "__main__":
    main()
