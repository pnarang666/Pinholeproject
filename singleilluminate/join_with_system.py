"""
Makes illumination one more comparable axis in stage3_integrated's combined grid,
instead of living only in stage3a's/singleilluminate's own outputs.

Does NOT modify any stage3_integrated .py file (read-only library, same rule as
stage1_v2/stage2/stage2_fixed/stage3a/stage3_human_vision) -- only IMPORTS
combine_metrics.build_combined_grid() (the function stage3_integrated itself already
uses to build its 105-point grid) and writes NEW output files into
stage3_integrated/outputs/, alongside (not replacing) the files stage3_integrated's
own scripts produce. Kept as a separate CSV/PNG rather than overwriting
combined_grid_550nm_12mm.csv, since that file is regenerated by
stage3_integrated/combine_metrics.py itself (owned by that stage) and would silently
drop this addition on its next run if this script wrote into it directly.

Does NOT recompute constrained_optimum_all_metrics()'s brightness-floor-constrained
optimization -- that logic already exists in combine_metrics.py and already consumes
an illumination column (relative_retinal_illuminance). This script's only job is
adding the raw percent_illumination number as a first-class column.
"""

import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

_STAGE3_INTEGRATED_DIR = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "stage3_integrated"))
if _STAGE3_INTEGRATED_DIR not in sys.path:
    sys.path.insert(0, _STAGE3_INTEGRATED_DIR)

import combine_metrics  # noqa: E402 (stage3_integrated -- imported, not modified)

import illumination_model  # this module

OUT_DIR = os.path.join(_STAGE3_INTEGRATED_DIR, "outputs")


def build_grid_with_illumination():
    """
    stage3_integrated's own 105-point combined grid (built via its own
    build_combined_grid(), not re-derived here) + one new column,
    percent_illumination, from singleilluminate's unified interface. Row count is
    asserted unchanged before/after, same discipline build_combined_grid() itself
    already uses for its own merge.
    """
    df = combine_metrics.build_combined_grid()
    n_before = len(df)

    df = df.copy()
    df["percent_illumination"] = [
        illumination_model.percent_illumination(row.a_hole_um, row.D_pupil_um)["percent_illumination"]
        for row in df.itertuples()
    ]

    if len(df) != n_before:
        raise ValueError(f"Row count changed while adding percent_illumination: "
                          f"{n_before} -> {len(df)}. This should be impossible (a "
                          f"per-row apply, not a join that can fan out) -- investigate "
                          f"before trusting this output.")

    # Cross-check, not silently assumed: percent_illumination (this module, via
    # stage3a/transmission.py) vs the grid's own pre-existing
    # relative_retinal_illuminance column (from stage3_human_vision/photometry.py) --
    # already established identical by stage3_integrated/README.md and by
    # illumination_model.py's own import-time self-check; re-verified directly here
    # on the actual joined data, not just at a few hand-picked test points.
    max_abs_diff = (df["percent_illumination"] - df["relative_retinal_illuminance"]).abs().max()
    if max_abs_diff > 1e-9:
        raise ValueError(f"percent_illumination diverges from the grid's existing "
                          f"relative_retinal_illuminance column by up to {max_abs_diff} "
                          f"-- expected exact agreement (both trace to the same "
                          f"(a_hole/D_pupil)^2 formula, see illumination_model.py).")

    return df


def plot_illumination_heatmap(df, out_path):
    """
    ONE comparison figure, on the SAME axes/subplot layout as
    stage3_integrated/generate_plots.py::plot_sensitivity_heatmaps (aperture x
    myopia, imshow/viridis/pivot_table) -- a single panel matching that exact
    convention, not a one-off chart style, so illumination reads the same way as
    every other metric's sensitivity heatmap in this project.

    Expected/honest result, not a bug: percent_illumination depends only on
    (a_hole_um, D_pupil_um) -- NOT on M_diopters (pinhole transmission is a purely
    geometric area-ratio, independent of the eye's myopia/defocus state). Every
    column of this heatmap is therefore constant across the M axis. This is stated
    explicitly in the plot title rather than left to look like a rendering error.
    """
    pivot = df.pivot_table(index="M_diopters", columns="a_hole_um", values="percent_illumination")
    fig, ax = plt.subplots(figsize=(9, 6.5))
    im = ax.imshow(pivot.values * 100, aspect="auto", origin="lower", cmap="viridis",
                    extent=[pivot.columns.min(), pivot.columns.max(), pivot.index.min(), pivot.index.max()])
    ax.set_xlabel("aperture (µm)")
    ax.set_ylabel("M (diopters)")
    ax.set_title("percent_illumination (%) -- aperture x myopia\n"
                 "(constant across M by construction: a purely geometric area\n"
                 "ratio, not a wave-optics/defocus quantity)", fontsize=10)
    fig.colorbar(im, ax=ax, label="percent_illumination (%)", fraction=0.046)

    # Brightness-floor reference: annotate the two apertures nearest the 6.25%/9%
    # floors this project designs around (stage3a/README.md), so the heatmap reads
    # alongside those same two numbers everywhere else they appear in this project.
    for floor, label in ((illumination_model.BRIGHTNESS_FLOOR_LOW, "6.25%"),
                          (illumination_model.BRIGHTNESS_FLOOR_HIGH, "9%")):
        row0 = df[np.isclose(df["M_diopters"], df["M_diopters"].min())].sort_values("a_hole_um")
        idx = (row0["percent_illumination"] - floor).abs().idxmin()
        a_at_floor = row0.loc[idx, "a_hole_um"]
        ax.axvline(a_at_floor, color="white", linestyle="--", linewidth=1, alpha=0.8)
        ax.text(a_at_floor, pivot.index.max(), f" {label}", color="white", fontsize=8,
                va="top", rotation=90)

    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    df = build_grid_with_illumination()
    csv_path = os.path.join(OUT_DIR, "combined_grid_with_illumination.csv")
    df.to_csv(csv_path, index=False)
    print(f"Wrote {csv_path} ({len(df)} rows, {len(df.columns)} columns -- "
          f"stage3_integrated's own combined_grid_550nm_12mm.csv columns + "
          f"percent_illumination)")
    print("Confirmed: percent_illumination agrees EXACTLY with the grid's existing "
          "relative_retinal_illuminance column (both trace to the same formula, see "
          "illumination_model.py's cross-check) -- this new column adds explicit "
          "singleilluminate provenance, not a numerically new value.")

    fig_path = os.path.join(OUT_DIR, "illumination_sensitivity_heatmap.png")
    plot_illumination_heatmap(df, fig_path)
    print(f"Wrote {fig_path}")

    print()
    print("NOTE: this covers single-hole illumination only. Multi-hole array "
          "illumination is NOT joined here because stage_array/ does not exist in "
          "this project -- see illumination_model.py's module docstring. Nothing "
          "about array illumination is silently omitted from a table that should "
          "have it; it was never computed in the first place.")


if __name__ == "__main__":
    main()
